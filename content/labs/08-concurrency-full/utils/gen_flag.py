"""Write the flag.h of a challenge of session 08.

    gen_flag.py <flag-file> <proof>... > flag.h

The flag is encrypted with a stream of bytes seeded from a key and from the
"proof": the numbers a correct run of the challenge ends with, in the order
in which chall.c passes them to flag_print().  The key is derived from the
flag, so the same flag always gives the same flag.h.

publish.sh makes the copy of flag.h that students get, with the key left
out, next to an executable built from the complete one.
"""

import hashlib
import struct
import sys

FNV_OFFSET = 2166136261
FNV_PRIME = 16777619
MASK = 0xFFFFFFFF

HEADER = """\
/* SPDX-License-Identifier: BSD-3-Clause */

/*
 * The flag of this challenge, encrypted, and the code that decrypts it.
 *
 * The flag is decrypted with a stream of bytes that depends on two things:
 * the key below, and the numbers the run ended with (the "proof": how many
 * items came out, their sum, and so on).  A run that ended with other
 * numbers than the expected ones gives another stream, and no flag.
 *
 * Generated by utils/gen_flag.py; do not edit.
 */

#ifndef FLAG_H_
#define FLAG_H_		1

#include <stdint.h>
#include <stdio.h>

#define FLAG_SEED	2166136261u
"""

FOOTER = """\
/* FNV-1a, 32 bits: a small hash function. */
static uint32_t flag_hash(uint32_t hash, const void *data, size_t len)
{
	const unsigned char *bytes = data;
	size_t i;

	for (i = 0; i < len; i++) {
		hash ^= bytes[i];
		hash *= 16777619u;
	}

	return hash;
}

/*
 * Decrypt the flag with the key and the proof, and print it if what came
 * out is the flag.  Returns 0 if it was, 1 if not.
 */
static int flag_print(const uint64_t *proof, size_t count)
{
	char flag[sizeof(flag_enc) + 1];
	uint32_t state;
	size_t i;

	state = flag_hash(FLAG_SEED, flag_key, sizeof(flag_key));
	state = flag_hash(state, proof, count * sizeof(*proof));
	if (state == 0)
		state = 1;

	/* xorshift32: one pseudo-random byte for every byte of the flag. */
	for (i = 0; i < sizeof(flag_enc); i++) {
		state ^= state << 13;
		state ^= state >> 17;
		state ^= state << 5;
		flag[i] = flag_enc[i] ^ (state & 0xff);
	}
	flag[i] = '\\0';

	if (flag_hash(FLAG_SEED, flag, sizeof(flag_enc)) != flag_check) {
		printf("No flag: the run did not end with the expected numbers.\\n");
		return 1;
	}

	printf("flag: %s\\n", flag);

	return 0;
}

#endif
"""


def fnv(state, data):
    for byte in data:
        state ^= byte
        state = (state * FNV_PRIME) & MASK
    return state


def c_array(name, data):
    lines = [f"static const unsigned char {name}[] = {{"]
    for i in range(0, len(data), 8):
        row = ", ".join(f"0x{byte:02x}" for byte in data[i:i + 8])
        lines.append(f"\t{row},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    args = sys.argv[1:]
    if not args:
        sys.exit(__doc__)

    with open(args[0], "rb") as flag_file:
        flag = flag_file.read().strip()
    proof = b"".join(struct.pack("<Q", int(arg)) for arg in args[1:])
    key = hashlib.sha256(b"so-session-08:" + flag).digest()[:16]

    state = fnv(fnv(FNV_OFFSET, key), proof) or 1
    enc = bytearray()
    for byte in flag:
        state ^= (state << 13) & MASK
        state ^= state >> 17
        state ^= (state << 5) & MASK
        enc.append(byte ^ (state & 0xFF))

    out = [HEADER]
    out.append(c_array("flag_key", key))
    out.append(c_array("flag_enc", enc))
    out.append(f"static const uint32_t flag_check = 0x{fnv(FNV_OFFSET, flag):08x};\n")
    out.append(FOOTER)
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
